"use client";

import * as React from "react";
import { AnimatePresence, motion } from "framer-motion";
import {
  ArrowRight,
  CheckCircle2,
  Filter,
  Hand,
  ListOrdered,
  Pause,
  Play,
  RotateCcw,
  Rows3,
  UserPlus,
} from "lucide-react";
import Link from "next/link";
import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { Separator, Progress, stagger, riseItem } from "@/components/ui/primitives";
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from "@/components/ui/select";
import { PageHeader, EmptyState } from "@/components/shared/page-header";
import { MetricCard, Sparkline } from "@/components/shared/metric-card";
import {
  AcuityBadge,
  ClassificationPill,
  DecisionSupportDisclaimer,
  DemoTag,
  Freshness,
  QueueStatusChip,
  SignalDot,
  StageChip,
} from "@/components/shared/status";
import { selectCounts, useQueueStore } from "@/lib/store/queue-store";
import { useSystemStore } from "@/lib/store/system-store";
import { DEPARTMENTS, DEPARTMENT_OPTIONS } from "@/lib/mock/departments";
import type { QueueStage, QueueTicket } from "@/lib/types";
import { DEMO_BANNER } from "@/lib/types";
import { cn, formatMinutes } from "@/lib/utils";

const ease = [0.22, 1, 0.36, 1] as const;

const STAGES: QueueStage[] = ["REGISTERED", "TRIAGE", "IMAGING", "LAB", "CONSULT", "DISCHARGE"];

const STAGE_META: Record<QueueStage, { label: string; sub: string }> = {
  REGISTERED: { label: "Registered", sub: "Packet staged" },
  TRIAGE: { label: "Triage", sub: "Awaiting observation review" },
  IMAGING: { label: "Imaging", sub: "Modality slot held" },
  LAB: { label: "Laboratory", sub: "Panel on worklist" },
  CONSULT: { label: "Consult", sub: "Clinician review" },
  DISCHARGE: { label: "Discharge", sub: "Disposition drafted" },
};

const FILTERS = ["ALL", "WAITING", "IN_PROGRESS", "ON_HOLD", "COMPLETE"] as const;
type FilterKey = (typeof FILTERS)[number];

const FILTER_LABEL: Record<FilterKey, string> = {
  ALL: "All tickets",
  WAITING: "Waiting",
  IN_PROGRESS: "In progress",
  ON_HOLD: "On hold",
  COMPLETE: "Complete",
};

const CLINICIANS = [
  "Dr. Ilse Brandt",
  "Dr. Marcus Oyelaran",
  "Dr. Priya Raghunathan",
  "Dr. Hana Lindqvist",
  "Dr. Amara Okonkwo",
  "N. Ferreira, RN",
];

export default function QueuePage() {
  const tickets = useQueueStore((s) => s.tickets);
  const movements = useQueueStore((s) => s.movements);
  const counts = useQueueStore(selectCounts);
  const advance = useQueueStore((s) => s.advance);
  const toggleHold = useQueueStore((s) => s.toggleHold);
  const assign = useQueueStore((s) => s.assign);
  const reset = useQueueStore((s) => s.reset);

  const running = useSystemStore((s) => s.simulationRunning);
  const speed = useSystemStore((s) => s.speed);
  const toggleRunning = useSystemStore((s) => s.toggleRunning);

  const [filter, setFilter] = React.useState<FilterKey>("ALL");
  const [dept, setDept] = React.useState<string>("ALL");
  const [view, setView] = React.useState<"lanes" | "table">("lanes");

  const filtered = React.useMemo(() => {
    return tickets.filter((t) => {
      const okStatus = filter === "ALL" || t.status === filter;
      const okDept = dept === "ALL" || t.departmentId === dept;
      return okStatus && okDept;
    });
  }, [tickets, filter, dept]);

  return (
    <div className="space-y-6">
      <PageHeader
        eyebrow={
          <span className="flex items-center gap-2">
            <SignalDot tone={running ? "mint" : "amber"} pulse={running} />
            {running ? `Simulating at ${speed || 0}×` : "Simulation paused"} · {DEMO_BANNER}
          </span>
        }
        title="Live Queue Board"
        description="Simulated tickets advancing through six workflow stages. Movement is generated by a local timer — no queue system is connected."
        actions={
          <>
            <Button variant="secondary" onClick={toggleRunning}>
              {running ? <Pause className="h-4 w-4" /> : <Play className="h-4 w-4" />}
              {running ? "Pause" : "Resume"}
            </Button>
            <Button variant="ghost" onClick={reset}>
              <RotateCcw className="h-4 w-4" />
              Reset board
            </Button>
            <DemoTag />
          </>
        }
      />

      {/* ── Counters ──────────────────────────────────────────────── */}
      <div className="grid gap-3 sm:grid-cols-2 xl:grid-cols-5">
        <MetricCard
          index={0}
          label="Waiting"
          value={counts.waiting}
          icon={ListOrdered}
          tone="amber"
          delta={-4}
          deltaInvert
          spark={[46, 44, 43, 41, 40, 39, 38, counts.waiting]}
          caption="in lane"
        />
        <MetricCard
          index={1}
          label="In progress"
          value={counts.inProgress}
          icon={ArrowRight}
          tone="cyan"
          delta={3}
          spark={[5, 6, 6, 7, 7, 8, 8, counts.inProgress]}
          caption="being worked"
        />
        <MetricCard
          index={2}
          label="On hold"
          value={counts.onHold}
          icon={Hand}
          tone="slate"
          spark={[2, 2, 3, 2, 2, 3, 2, counts.onHold]}
          caption="attention"
        />
        <MetricCard
          index={3}
          label="Completed"
          value={counts.complete}
          icon={CheckCircle2}
          tone="mint"
          delta={6}
          spark={[1, 2, 3, 4, 5, 6, 7, counts.complete]}
          caption="this session"
        />
        <MetricCard
          index={4}
          label="Mean wait"
          value={Math.round(counts.avgWait)}
          unit="min"
          icon={Filter}
          tone={counts.avgWait > 30 ? "red" : "blue"}
          delta={-2}
          deltaInvert
          spark={[34, 33, 32, 31, 30, 29, 28, Math.round(counts.avgWait)]}
          caption="active tickets"
        />
      </div>

      {/* ── Toolbar ───────────────────────────────────────────────── */}
      <Card>
        <CardContent className="flex flex-wrap items-center gap-3 p-4">
          <div className="flex flex-wrap gap-1.5">
            {FILTERS.map((f) => (
              <button
                key={f}
                type="button"
                onClick={() => setFilter(f)}
                aria-pressed={filter === f}
                className={cn(
                  "rounded-md border px-2.5 py-1.5 text-[11px] font-bold uppercase tracking-wider transition-all focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-cyan/40",
                  filter === f
                    ? "border-cyan-400/50 bg-cyan-400/12 text-cyan-200"
                    : "border-white/10 bg-midnight/50 text-slate-400 hover:border-white/25",
                )}
              >
                {FILTER_LABEL[f]}
                {f !== "ALL" && (
                  <span className="ml-1.5 mono-nums opacity-70">
                    {tickets.filter((t) => t.status === f).length}
                  </span>
                )}
              </button>
            ))}
          </div>

          <div className="w-[220px]">
            <Select value={dept} onValueChange={setDept}>
              <SelectTrigger aria-label="Filter by department">
                <SelectValue />
              </SelectTrigger>
              <SelectContent>
                <SelectItem value="ALL">All departments</SelectItem>
                {DEPARTMENT_OPTIONS.map((d) => (
                  <SelectItem key={d.value} value={d.value}>
                    {d.label}
                  </SelectItem>
                ))}
              </SelectContent>
            </Select>
          </div>

          <div className="ml-auto flex items-center gap-1 rounded-lg border border-white/10 bg-midnight/60 p-1">
            {(["lanes", "table"] as const).map((v) => (
              <button
                key={v}
                type="button"
                onClick={() => setView(v)}
                aria-pressed={view === v}
                className={cn(
                  "flex items-center gap-1.5 rounded-md px-2.5 py-1.5 text-[11px] font-bold uppercase tracking-wider transition-colors focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-cyan/40",
                  view === v
                    ? "bg-white/[0.09] text-cyan-300"
                    : "text-slate-500 hover:text-slate-300",
                )}
              >
                {v === "lanes" ? <Rows3 className="h-3.5 w-3.5" /> : <ListOrdered className="h-3.5 w-3.5" />}
                {v}
              </button>
            ))}
          </div>
        </CardContent>
      </Card>

      {/* ── Board ─────────────────────────────────────────────────── */}
      {view === "lanes" ? (
        <LanesView
          tickets={filtered}
          onAdvance={advance}
          onHold={toggleHold}
          onAssign={assign}
        />
      ) : (
        <TableView
          tickets={filtered}
          onAdvance={advance}
          onHold={toggleHold}
          onAssign={assign}
        />
      )}

      {/* ── Movement log ──────────────────────────────────────────── */}
      <div className="grid gap-4 lg:grid-cols-[1.4fr_1fr]">
        <Card>
          <CardHeader className="flex-row items-center justify-between space-y-0">
            <CardTitle className="flex items-center gap-2">
              <SignalDot tone={running ? "cyan" : "slate"} pulse={running} />
              Movement log
            </CardTitle>
            <span className="text-[11px] text-slate-500">newest first</span>
          </CardHeader>
          <CardContent>
            <ul className="max-h-72 space-y-1.5 overflow-y-auto pr-1">
              <AnimatePresence initial={false}>
                {movements.slice(0, 24).map((m) => (
                  <motion.li
                    key={m.id}
                    initial={{ opacity: 0, x: -10 }}
                    animate={{ opacity: 1, x: 0 }}
                    exit={{ opacity: 0 }}
                    transition={{ duration: 0.25, ease }}
                    className="flex items-start gap-2.5 rounded-md px-2 py-1.5 odd:bg-white/[0.02]"
                  >
                    <span
                      className={cn(
                        "mt-1.5 h-1.5 w-1.5 shrink-0 rounded-full",
                        m.kind === "COMPLETE"
                          ? "bg-emerald-400"
                          : m.kind === "ON_HOLD"
                            ? "bg-slate-400"
                            : m.kind === "WAITING"
                              ? "bg-amber-400"
                              : "bg-cyan-400",
                      )}
                    />
                    <span className="flex-1 text-[12px] text-slate-400">{m.text}</span>
                    <Freshness at={m.at} />
                  </motion.li>
                ))}
              </AnimatePresence>
              {movements.length === 0 && (
                <li className="py-8 text-center text-xs text-slate-600">
                  Reset complete — resume the simulation to generate movement.
                </li>
              )}
            </ul>
          </CardContent>
        </Card>

        <Card>
          <CardHeader>
            <CardTitle>Stage distribution</CardTitle>
          </CardHeader>
          <CardContent className="space-y-3">
            {STAGES.map((s) => {
              const n = tickets.filter((t) => t.stage === s && t.status !== "COMPLETE").length;
              const pct = tickets.length ? (n / tickets.length) * 100 : 0;
              return (
                <div key={s}>
                  <div className="mb-1 flex items-baseline justify-between">
                    <span className="text-[12px] text-slate-300">{STAGE_META[s].label}</span>
                    <span className="text-[11px] font-semibold text-slate-400 mono-nums">{n}</span>
                  </div>
                  <Progress value={pct} indicator={s === "DISCHARGE" ? "mint" : "auto"} />
                </div>
              );
            })}
            <Separator />
            <DecisionSupportDisclaimer compact />
          </CardContent>
        </Card>
      </div>
    </div>
  );
}

/* ── Lane view ───────────────────────────────────────────────────────── */

function LaneActions({
  ticket,
  onAdvance,
  onHold,
  onAssign,
}: {
  ticket: QueueTicket;
  onAdvance: (id: string) => void;
  onHold: (id: string) => void;
  onAssign: (id: string, c: string) => void;
}) {
  const [pickerOpen, setPickerOpen] = React.useState(false);

  return (
    <div className="flex flex-wrap items-center gap-1.5">
      <Button
        size="sm"
        variant="secondary"
        onClick={() => onAdvance(ticket.id)}
        disabled={ticket.status === "COMPLETE"}
        aria-label={`Advance ${ticket.ticketCode}`}
      >
        <ArrowRight className="h-3.5 w-3.5" />
        Advance
      </Button>
      <Button
        size="sm"
        variant="ghost"
        onClick={() => onHold(ticket.id)}
        disabled={ticket.status === "COMPLETE"}
        aria-label={`Toggle hold for ${ticket.ticketCode}`}
      >
        <Hand className="h-3.5 w-3.5" />
        {ticket.status === "ON_HOLD" ? "Release" : "Hold"}
      </Button>
      <div className="relative">
        <Button
          size="sm"
          variant="ghost"
          onClick={() => setPickerOpen((v) => !v)}
          aria-label={`Assign ${ticket.ticketCode}`}
        >
          <UserPlus className="h-3.5 w-3.5" />
          Assign
        </Button>
        {pickerOpen && (
          <>
            <button
              type="button"
              className="fixed inset-0 z-20 cursor-default"
              aria-label="Close assign menu"
              onClick={() => setPickerOpen(false)}
            />
            <div className="absolute right-0 top-full z-30 mt-1 w-56 overflow-hidden rounded-lg border border-white/10 bg-navy p-1 shadow-panel">
              {CLINICIANS.map((c) => (
                <button
                  key={c}
                  type="button"
                  onClick={() => {
                    onAssign(ticket.id, c);
                    setPickerOpen(false);
                  }}
                  className="flex w-full items-center gap-2 rounded-md px-2.5 py-2 text-left text-[12px] text-slate-300 transition-colors hover:bg-cyan/10 hover:text-cyan-200"
                >
                  {c}
                </button>
              ))}
            </div>
          </>
        )}
      </div>
    </div>
  );
}

function TicketCard({
  ticket,
  onAdvance,
  onHold,
  onAssign,
  index,
}: {
  ticket: QueueTicket;
  onAdvance: (id: string) => void;
  onHold: (id: string) => void;
  onAssign: (id: string, c: string) => void;
  index: number;
}) {
  const dept = DEPARTMENTS.find((d) => d.id === ticket.departmentId);
  const urgent = ticket.classification === "IMMEDIATE CLINICAL REVIEW";
  const longWait = ticket.waitMinutes > 40;

  return (
    <motion.article
      layout
      initial={{ opacity: 0, y: 12 }}
      animate={{ opacity: 1, y: 0 }}
      exit={{ opacity: 0, scale: 0.97 }}
      transition={{ duration: 0.35, delay: Math.min(index * 0.03, 0.2), ease }}
      className={cn(
        "rounded-lg border bg-slate-800/60 p-3 transition-colors",
        urgent
          ? "border-red-500/35 hover:border-red-500/55"
          : longWait
            ? "border-amber-400/30 hover:border-amber-400/50"
            : "border-white/[0.07] hover:border-cyan-400/30",
      )}
    >
      <div className="flex items-center gap-2">
        <span className="text-[11.5px] font-bold text-cyan-300 mono-nums">{ticket.ticketCode}</span>
        <AcuityBadge value={ticket.acuity} />
        <QueueStatusChip status={ticket.status} />
        <span className="ml-auto text-[11px] text-slate-500 mono-nums">
          {formatMinutes(ticket.waitMinutes)}
        </span>
      </div>

      <p className="mt-2 truncate text-[13px] font-medium text-slate-100">{ticket.displayName}</p>
      <p className="truncate text-[11px] text-slate-500">
        {ticket.age}y · {ticket.sex} · {dept?.code} · {ticket.zone}
      </p>

      <div className="mt-2 flex flex-wrap items-center gap-1.5">
        <ClassificationPill value={ticket.classification} size="sm" />
        <StageChip stage={ticket.stage} />
      </div>

      <p className="mt-2 truncate text-[11px] text-slate-500">
        {ticket.clinician ?? <span className="text-amber-300/80">unassigned</span>} · {ticket.note}
      </p>

      <Separator className="my-2.5" />

      <LaneActions
        ticket={ticket}
        onAdvance={onAdvance}
        onHold={onHold}
        onAssign={onAssign}
      />
    </motion.article>
  );
}

function LanesView({
  tickets,
  onAdvance,
  onHold,
  onAssign,
}: {
  tickets: QueueTicket[];
  onAdvance: (id: string) => void;
  onHold: (id: string) => void;
  onAssign: (id: string, c: string) => void;
}) {
  if (tickets.length === 0) {
    return (
      <EmptyState
        icon={ListOrdered}
        title="No tickets match these filters"
        description="Adjust the status or department filter to bring tickets back onto the board."
      />
    );
  }

  return (
    <div className="grid gap-3 md:grid-cols-2 xl:grid-cols-3 2xl:grid-cols-6">
      {STAGES.map((stage) => {
        const lane = tickets.filter((t) => t.stage === stage);
        return (
          <section
            key={stage}
            className="flex min-w-0 flex-col rounded-xl border border-white/[0.06] bg-navy/60"
          >
            <header className="flex items-center justify-between gap-2 border-b border-white/[0.06] px-3 py-2.5">
              <div className="min-w-0">
                <h3 className="truncate text-[11.5px] font-bold uppercase tracking-wider text-slate-200">
                  {STAGE_META[stage].label}
                </h3>
                <p className="truncate text-[10px] text-slate-600">{STAGE_META[stage].sub}</p>
              </div>
              <span className="shrink-0 rounded-md border border-white/10 bg-white/[0.04] px-1.5 py-0.5 text-[10.5px] font-bold text-slate-300 mono-nums">
                {lane.length}
              </span>
            </header>

            <div className="flex-1 space-y-2 p-2.5">
              <AnimatePresence mode="popLayout">
                {lane.map((t, i) => (
                  <TicketCard
                    key={t.id}
                    ticket={t}
                    index={i}
                    onAdvance={onAdvance}
                    onHold={onHold}
                    onAssign={onAssign}
                  />
                ))}
              </AnimatePresence>
              {lane.length === 0 && (
                <p className="rounded-lg border border-dashed border-white/10 px-3 py-6 text-center text-[11px] text-slate-600">
                  Lane empty
                </p>
              )}
            </div>
          </section>
        );
      })}
    </div>
  );
}

/* ── Table view ──────────────────────────────────────────────────────── */

function TableView({
  tickets,
  onAdvance,
  onHold,
  onAssign,
}: {
  tickets: QueueTicket[];
  onAdvance: (id: string) => void;
  onHold: (id: string) => void;
  onAssign: (id: string, c: string) => void;
}) {
  if (tickets.length === 0) {
    return (
      <EmptyState
        icon={ListOrdered}
        title="No tickets match these filters"
        description="Adjust the status or department filter to bring tickets back onto the board."
      />
    );
  }

  return (
    <Card>
      <CardContent className="p-0">
        <div className="overflow-x-auto">
          <table className="w-full min-w-[900px] text-sm">
            <thead>
              <tr className="border-b border-white/[0.07]">
                {["Ticket", "Subject", "Acuity", "Classification", "Stage", "Status", "Wait", "Owner", "Actions"].map(
                  (h) => (
                    <th
                      key={h}
                      className="px-3 py-2.5 text-left text-[10px] font-semibold uppercase tracking-[0.14em] text-slate-500 first:pl-5"
                    >
                      {h}
                    </th>
                  ),
                )}
              </tr>
            </thead>
            <tbody className="divide-y divide-white/[0.05]">
              {tickets.map((t, i) => (
                <motion.tr
                  key={t.id}
                  initial={{ opacity: 0 }}
                  animate={{ opacity: 1 }}
                  transition={{ delay: Math.min(i * 0.02, 0.2) }}
                  className="transition-colors hover:bg-white/[0.03]"
                >
                  <td className="px-3 py-2.5 pl-5 text-[12px] font-bold text-cyan-300 mono-nums">
                    {t.ticketCode}
                  </td>
                  <td className="px-3 py-2.5">
                    <span className="block text-[12.5px] text-slate-200">{t.displayName}</span>
                    <span className="block text-[10.5px] text-slate-600 mono-nums">{t.mrn}</span>
                  </td>
                  <td className="px-3 py-2.5">
                    <AcuityBadge value={t.acuity} />
                  </td>
                  <td className="px-3 py-2.5">
                    <ClassificationPill value={t.classification} size="sm" />
                  </td>
                  <td className="px-3 py-2.5">
                    <StageChip stage={t.stage} />
                  </td>
                  <td className="px-3 py-2.5">
                    <QueueStatusChip status={t.status} />
                  </td>
                  <td className="px-3 py-2.5 text-[12px] text-slate-300 mono-nums">
                    {formatMinutes(t.waitMinutes)}
                  </td>
                  <td className="max-w-[160px] truncate px-3 py-2.5 text-[12px] text-slate-400">
                    {t.clinician ?? <span className="text-amber-300/80">unassigned</span>}
                  </td>
                  <td className="px-3 py-2.5">
                    <LaneActions
                      ticket={t}
                      onAdvance={onAdvance}
                      onHold={onHold}
                      onAssign={onAssign}
                    />
                  </td>
                </motion.tr>
              ))}
            </tbody>
          </table>
        </div>
      </CardContent>
      <div className="border-t border-white/[0.06] px-5 py-3">
        <Badge variant="muted">{DEMO_BANNER} — rows are fictional</Badge>
      </div>
    </Card>
  );
}
